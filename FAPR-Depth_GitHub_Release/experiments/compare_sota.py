r"""
FAPR-Depth v6 unified comparison table builder
==============================================

Purpose
-------
Compare the current FAPR-Depth v6 complete-test result with the same external methods used
by the previous TAGE-Depth comparison route:

    Raw Depth, DFNet, TODE-Trans, TDCNet, SwinDRNet, FDCT, ReMake,
    FAPR-Depth (Ours)

The script has two modes.

1) summary (default, very fast)
   - reads the already generated FAPR test summary;
   - searches previous unified baseline CSV files;
   - writes comparison CSV/Markdown/LaTeX/JSON tables;
   - performs no neural-network inference.

2) direct
   - still reuses the completed FAPR summary;
   - directly evaluates TODE-Trans, TDCNet and SwinDRNet through the verified
     local wrapper scripts under the same cache split, transparent-mask fusion,
     and sample-mean metric implementation;
   - DFNet and ReMake are loaded from their unified summary CSV files;
   - direct external results are cached, so the next run is fast.

Recommended first run
---------------------
    python compare_fapr_depth_v6_with_baselines.py

Formal direct comparison
------------------------
    python compare_fapr_depth_v6_with_baselines.py --mode direct

Quick direct smoke test (not a formal full-split table)
-------------------------------------------------------
    python compare_fapr_depth_v6_with_baselines.py --mode direct --max-shards 10

Important protocol note
-----------------------
CSV-merged results are comparable only when they were produced on the same split,
transparent-mask evaluation region, raw-depth-preserving fusion protocol, image
resolution, and sample-mean aggregation. The script records every selected source
CSV so that protocol mismatches are visible instead of silently hidden.
"""

