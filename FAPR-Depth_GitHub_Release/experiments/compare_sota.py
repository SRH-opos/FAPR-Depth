def load_external_summary_rows(
    csv_paths: Sequence[Path],
) -> Tuple[Dict[str, Dict[str, float]], Dict[str, str], List[str]]:
    candidates: List[Tuple[Path, Dict[str, Any]]] = []
    for path in csv_paths:
        for row in load_csv_rows(path):
            candidates.append((path, row))

    found: Dict[str, Dict[str, float]] = {}
    sources: Dict[str, str] = {}
    notes: List[str] = []

    for method, pattern_groups in EXTERNAL_METHOD_SPECS.items():
        best: Optional[Tuple[int, Path, str, Dict[str, float]]] = None
        for source_path, raw_row in candidates:
            name = row_name(raw_row)
            if not name:
                continue
            low = name.lower()
            # Avoid diagnostic/raw/old-model rows being selected as a method result.
            if "old base" in low or "previous model" in low or "oracle" in low:
                continue
            if "raw depth" in low:
                continue
            for rank, patterns in enumerate(pattern_groups):
                if not name_matches(name, patterns):
                    continue
                metrics = standardize_metrics(raw_row)
                if not any(k in metrics for k in ["mae_mask", "rmse_mask", "rel_mask"]):
                    continue
                richness = sum(finite_float(metrics.get(k)) is not None for k in metrics)
                score = 1000 - 100 * rank + 10 * richness + protocol_bonus(raw_row, source_path)
                if best is None or score > best[0]:
                    best = (score, source_path, name, metrics)
        if best is None:
            notes.append(f"[missing summary] {method}: no usable row found")
        else:
            _, source_path, selected_name, metrics = best
            found[method] = metrics
            sources[method] = str(source_path)
            notes.append(f"[external summary] {method} <- `{selected_name}` from {source_path}")
    return found, sources, notes


