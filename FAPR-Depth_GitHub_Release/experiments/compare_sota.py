_DIRECT_EXTERNAL_CACHE: Optional[Dict[str, Any]] = None


def purge_external_imports() -> None:
    # External repositories commonly use generic top-level module names.
    prefixes = [
        "inference", "models", "utils", "datasets", "config", "configs",
        "networks", "trainer", "module", "model", "options", "data_loader",
    ]
    for name in list(sys.modules.keys()):
        if name in prefixes or any(name.startswith(prefix + ".") for prefix in prefixes):
            del sys.modules[name]


def prepend_path(path: Path) -> None:
    text = str(Path(path))
    if text in sys.path:
        sys.path.remove(text)
    sys.path.insert(0, text)


def find_function(module, candidate_names: Sequence[str]):
    for name in candidate_names:
        value = getattr(module, name, None)
        if callable(value):
            return value
    raise AttributeError(f"No compatible function in {module.__name__}; tried {list(candidate_names)}")


def load_direct_external_models(requested_models: Sequence[str]) -> Dict[str, Any]:
    global _DIRECT_EXTERNAL_CACHE
    cache_key = tuple(sorted(requested_models))
    if _DIRECT_EXTERNAL_CACHE is not None and _DIRECT_EXTERNAL_CACHE.get("key") == cache_key:
        return _DIRECT_EXTERNAL_CACHE

    configurations = {
        "TODE-Trans": {
            "root": TODE_ROOT,
            "script": TODE_SCRIPT,
            "module": "fapr_direct_tode_wrapper",
            "loader_names": ["load_tode_inferencer", "load_tode_model", "load_inferencer"],
            "infer_names": ["infer_tode", "infer_tode_trans", "run_tode_inference"],
        },
        "TDCNet": {
            "root": TDCNET_ROOT,
            "script": TDCNET_SCRIPT,
            "module": "fapr_direct_tdcnet_wrapper",
            "loader_names": [
                "load_tdcnet_inferencer", "load_tdc_inferencer",
                "load_tdcnet_model", "load_tdc_model", "load_inferencer",
            ],
            "infer_names": [
                "infer_tdcnet", "infer_tdc", "run_tdcnet_inference", "run_tdc_inference",
            ],
        },
        "SwinDRNet": {
            "root": DREDS_ROOT,
            "script": DREDS_SCRIPT,
            "module": "fapr_direct_swindrnet_wrapper",
            "loader_names": ["load_dreds_model", "load_swindrnet_model"],
            "infer_names": ["infer_dreds", "infer_swindrnet"],
        },
    }

    models: Dict[str, Any] = {}
    failures: Dict[str, str] = {}
    for method in requested_models:
        cfg = configurations.get(method)
        if cfg is None:
            failures[method] = "Unsupported direct method"
            continue
        try:
            root = Path(cfg["root"])
            script = Path(cfg["script"])
            if not root.exists():
                raise FileNotFoundError(f"repository root not found: {root}")
            if not script.exists():
                raise FileNotFoundError(f"wrapper script not found: {script}")
            purge_external_imports()
            prepend_path(root)
            module = import_module_from_path(str(cfg["module"]), script)
            load_fn = find_function(module, cfg["loader_names"])
            infer_fn = find_function(module, cfg["infer_names"])
            print(f"[Direct load] {method} ...")
            model = load_fn()
            if hasattr(model, "eval"):
                model.eval()
            models[method] = {"model": model, "infer": infer_fn}
            print(f"[Direct load] {method}: OK")
        except Exception as exc:
            failures[method] = repr(exc)
            print(f"[WARN] Direct loading failed for {method}: {exc!r}")

    _DIRECT_EXTERNAL_CACHE = {"key": cache_key, "models": models, "failures": failures}
    return _DIRECT_EXTERNAL_CACHE


def resize_external_prediction(prediction: Any, raw_shape: Tuple[int, int]) -> np.ndarray:
    pred = np.asarray(prediction, dtype=np.float32)
    pred = np.squeeze(pred)
    height, width = raw_shape
    if pred.ndim == 3:
        if pred.shape[-1] == 1:
            pred = pred[..., 0]
        elif pred.shape[0] == 1:
            pred = pred[0]
        elif pred.shape[-1] == 3:
            pred = cv2.cvtColor(pred.astype(np.float32), cv2.COLOR_RGB2GRAY)
        elif pred.shape[0] == 3:
            pred = pred.mean(axis=0)
    if pred.ndim != 2:
        raise RuntimeError(f"Cannot interpret external prediction shape {pred.shape}")
    if pred.shape != (height, width):
        pred = cv2.resize(pred, (width, height), interpolation=cv2.INTER_NEAREST)
    pred = pred.astype(np.float32)
    pred[~np.isfinite(pred)] = 0.0
    return pred


def infer_tode_or_tdc(fn, model, rgb: np.ndarray, raw: np.ndarray, mask: np.ndarray) -> np.ndarray:
    attempts = [
        lambda: fn(model, rgb, raw, use_bgr=False),
        lambda: fn(model, rgb, raw, mask, use_bgr=False),
        lambda: fn(model, rgb, raw),
        lambda: fn(model, rgb, raw, mask),
    ]
    last_error: Optional[Exception] = None
    for attempt in attempts:
        try:
            return resize_external_prediction(attempt(), raw.shape)
        except TypeError as exc:
            last_error = exc
    raise RuntimeError(f"No compatible inference signature: {last_error}")


def infer_swindr(fn, model, rgb: np.ndarray, raw: np.ndarray, mask: np.ndarray) -> np.ndarray:
    try:
        pred = fn(model, rgb, raw)
    except TypeError:
        pred = fn(model, rgb, raw, mask)
    return resize_external_prediction(pred, raw.shape)


def tensor_sample_to_numpy(
    rgb_tensor: torch.Tensor,
    raw_tensor: torch.Tensor,
    mask_tensor: torch.Tensor,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    rgb = rgb_tensor.detach().float().cpu().numpy()
    raw = np.squeeze(raw_tensor.detach().float().cpu().numpy()).astype(np.float32)
    mask = np.squeeze(mask_tensor.detach().float().cpu().numpy()).astype(np.float32)
    if rgb.ndim == 3 and rgb.shape[0] == 3:
        rgb = np.transpose(rgb, (1, 2, 0))
    rgb = np.clip(rgb.astype(np.float32), 0.0, 1.0)
    return rgb, raw, mask


def parse_direct_models(text: str) -> List[str]:
    if text.strip().lower() in {"all", "*"}:
        return ["TODE-Trans", "TDCNet", "SwinDRNet"]
    aliases = {
        "tode": "TODE-Trans", "tode-trans": "TODE-Trans",
        "tdc": "TDCNet", "tdcnet": "TDCNet",
        "swin": "SwinDRNet", "swindrnet": "SwinDRNet", "dreds": "SwinDRNet",
    }
    result: List[str] = []
    for token in text.split(","):
        key = token.strip().lower()
        if not key:
            continue
        method = aliases.get(key, token.strip())
        if method not in result:
            result.append(method)
    return result


def direct_cache_path(out_dir: Path, split: str, max_shards: int, models: Sequence[str]) -> Path:
    subset = "all" if max_shards <= 0 else f"{max_shards}shards"
    model_key = "_".join(m.lower().replace("-", "").replace(" ", "") for m in models)
    return out_dir / f"direct_external_{split}_{subset}_{model_key}.csv"


def evaluate_direct_external(
    split: str,
    max_shards: int,
    requested_models: Sequence[str],
    out_dir: Path,
    force: bool,
) -> Tuple[Dict[str, Dict[str, float]], Dict[str, str], List[str]]:
    cache_path = direct_cache_path(out_dir, split, max_shards, requested_models)
    if cache_path.exists() and not force:
        cached = load_csv_rows(cache_path)
        rows = {row_name(r): standardize_metrics(r) for r in cached if row_name(r)}
        notes = [f"[direct cache] loaded {cache_path}"]
        sources = {method: str(cache_path) for method in rows}
        return rows, sources, notes

    if not TRAIN_SCRIPT.exists():
        raise FileNotFoundError(f"Current training script not found: {TRAIN_SCRIPT}")
    train_mod = import_module_from_path("fapr_v6_train_for_comparison", TRAIN_SCRIPT)
    train_mod.DEVICE = DEVICE
    train_mod.USE_AMP = USE_AMP
    train_mod.CACHE_ROOT = CACHE_ROOT

    max_n = None if max_shards <= 0 else max_shards
    shards = train_mod.load_split_shards(CACHE_ROOT, split, max_n)
    dataset = train_mod.CachedShardDataset(shards)
    loader = DataLoader(
        dataset,
        batch_size=LOADER_BATCH_SIZE,
        shuffle=False,
        num_workers=NUM_WORKERS,
        pin_memory=PIN_MEMORY,
        collate_fn=train_mod.ragged_shard_collate,
        persistent_workers=NUM_WORKERS > 0,
    )

    direct = load_direct_external_models(requested_models)
    models = direct["models"]
    failures = direct["failures"]
    if not models:
        raise RuntimeError(f"No direct external model could be loaded: {failures}")

    metric_lists: Dict[str, List[Dict[str, float]]] = {name: [] for name in models}
    sample_count = 0
    start = time.time()

    with torch.inference_mode():
        pbar = tqdm(loader, desc=f"Direct external {split}")
        for batch in pbar:
            batch = {
                key: value.to(DEVICE, non_blocking=True).float() if torch.is_tensor(value) else value
                for key, value in batch.items()
            }
            inp = train_mod.build_inputs(batch)
            rgb, raw = inp["rgb"], inp["raw"]
            gt, mask, valid = inp["gt"], inp["mask"], inp["valid"]
            batch_n = int(rgb.shape[0])

            for i in range(batch_n):
                rgb_np, raw_np, mask_np = tensor_sample_to_numpy(rgb[i], raw[i], mask[i])
                for method, item in models.items():
                    if method in {"TODE-Trans", "TDCNet"}:
                        pred_np = infer_tode_or_tdc(item["infer"], item["model"], rgb_np, raw_np, mask_np)
                    elif method == "SwinDRNet":
                        pred_np = infer_swindr(item["infer"], item["model"], rgb_np, raw_np, mask_np)
                    else:
                        continue
                    fused_np = raw_np.copy()
                    fused_np[mask_np > 0.5] = pred_np[mask_np > 0.5]
                    pred_tensor = torch.from_numpy(fused_np)[None, None].to(DEVICE)
                    metrics = train_mod.metric_values(
                        pred_tensor,
                        raw[i:i + 1],
                        gt[i:i + 1],
                        mask[i:i + 1],
                        valid[i:i + 1],
                    )
                    metric_lists[method].append(metrics)
                sample_count += 1
            pbar.set_postfix(samples=sample_count)
            del batch, inp

    elapsed = time.time() - start
    rows = {method: average_dicts(values) for method, values in metric_lists.items() if values}
    for metrics in rows.values():
        score = selection_score(metrics)
        if score is not None:
            metrics["score"] = score

    cache_rows = [{"method": method, **metrics} for method, metrics in rows.items()]
    write_csv(cache_path, cache_rows)
    meta = {
        "split": split,
        "max_shards": max_shards,
        "shards": len(shards),
        "samples": sample_count,
        "elapsed_seconds": elapsed,
        "models": list(rows.keys()),
        "failures": failures,
        "protocol": "sample-mean; transparent-mask metrics; raw-preserving mask fusion",
    }
    write_json(cache_path.with_suffix(".json"), meta)

    notes = [
        f"[direct] evaluated {', '.join(rows.keys())} on split={split}, "
        f"shards={len(shards)}, samples={sample_count}, elapsed={elapsed:.1f}s",
        f"[direct] cached results: {cache_path}",
    ]
    for method, error in failures.items():
        notes.append(f"[direct failure] {method}: {error}")
    sources = {method: str(cache_path) for method in rows}
    return rows, sources, notes


