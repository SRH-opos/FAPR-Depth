def load_current_rows(summary_path: Path) -> Tuple[Dict[str, Dict[str, float]], List[str]]:
    rows = load_csv_rows(summary_path)
    result: Dict[str, Dict[str, float]] = {}
    notes = [f"[current] loaded FAPR summary: {summary_path}"]

    if not rows:
        notes.append(f"[current missing] no readable rows in {summary_path}")
        return result, notes

    # Index each row by every available name-like field.  In particular, the
    # complete-test CSV stores labels such as ``FAPR-Depth v6 Safe (Ours)`` in
    # ``method`` and the internal stream name ``Safe benchmark`` in ``variant``.
    # Looking only at one of the columns is not sufficient.
    by_alias: Dict[str, Dict[str, Any]] = {}
    for row in rows:
        for alias in row_aliases(row):
            by_alias.setdefault(alias, row)

    observed_methods = [
        str(r.get("method", r.get("Method", ""))).strip()
        for r in rows
        if str(r.get("method", r.get("Method", ""))).strip()
    ]
    observed_variants = [
        str(r.get("variant", r.get("Variant", ""))).strip()
        for r in rows
        if str(r.get("variant", r.get("Variant", ""))).strip()
    ]
    notes.append(f"[current columns] {list(rows[0].keys())}")
    notes.append(f"[current methods] {observed_methods}")
    notes.append(f"[current variants] {observed_variants}")

    for source_label, method_name in CURRENT_VARIANT_MAP.items():
        row = by_alias.get(source_label)
        if row is None:
            notes.append(
                f"[current missing] label `{source_label}` is absent from {summary_path}; "
                f"available method labels={observed_methods}"
            )
            continue
        metrics = standardize_metrics(row)
        if metrics:
            result[method_name] = metrics
            matched_method = str(row.get("method", row.get("Method", ""))).strip()
            matched_variant = str(row.get("variant", row.get("Variant", ""))).strip()
            notes.append(
                f"[current] {method_name} <- method=`{matched_method}`, variant=`{matched_variant}`"
            )
        else:
            notes.append(f"[current missing metrics] `{source_label}` matched but had no usable metrics")
    return result, notes


