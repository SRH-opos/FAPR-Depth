def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Compare FAPR-Depth v6 with DFNet/TODE/TDCNet/SwinDRNet/FDCT/ReMake."
    )
    parser.add_argument("--mode", choices=["summary", "direct"], default="summary")
    parser.add_argument("--split", type=str, default="test")
    parser.add_argument("--region", choices=["mask", "all"], default="mask")
    parser.add_argument("--cache-root", type=str, default=str(CACHE_ROOT))
    parser.add_argument("--train-script", type=str, default=str(TRAIN_SCRIPT))
    parser.add_argument("--current-summary", type=str, default=str(CURRENT_SUMMARY))
    parser.add_argument("--out-dir", type=str, default=str(OUT_DIR_BASE))
    parser.add_argument(
        "--ours-variant",
        choices=tuple(OURS_VARIANTS.keys()),
        default="candidate",
        help=(
            "FAPR row used in the external-model main table. "
            "candidate is the fixed final paper model (safe anchor + detail proposal); "
            "safe and final are retained as ablations."
        ),
    )
    parser.add_argument(
        "--extra-summary-csv", action="append", default=[],
        help="Additional previous baseline summary CSV. May be repeated.",
    )
    parser.add_argument(
        "--direct-models", type=str, default="all",
        help="Comma-separated direct models: tode,tdcnet,swindrnet; default=all.",
    )
    parser.add_argument(
        "--max-shards", type=int, default=0,
        help="Direct mode only. 0 evaluates all shards; positive values are preview subsets.",
    )
    parser.add_argument(
        "--force-direct", action="store_true",
        help="Ignore cached direct external results and recompute.",
    )
    parser.add_argument(
        "--allow-recursive-scan",
        action="store_true",
        help=(
            "Use the broad legacy recursive scan. Normally unnecessary because the "
            "script now performs a restricted historical fallback automatically."
        ),
    )
    parser.add_argument(
        "--refresh-baseline-sources",
        action="store_true",
        help=(
            "Ignore the saved frozen_external_baseline_sources.json and rediscover "
            "historical baseline CSVs."
        ),
    )
    parser.add_argument(
        "--rediscover-external-baselines",
        action="store_true",
        help=(
            "Diagnostic only: ignore LOCKED_VERIFIED_BASELINES and select rows from "
            "historical CSV files. The default paper table never rediscover rows."
        ),
    )
    parser.add_argument(
        "--require-baselines",
        action="store_true",
        default=True,
        help="Fail when any expected external baseline row is missing.",
    )
    parser.add_argument(
        "--allow-missing-baselines",
        action="store_false",
        dest="require_baselines",
        help="Generate a partial table instead of failing on missing baseline rows.",
    )
    return parser.parse_args()


def main() -> None:
    global CACHE_ROOT, TRAIN_SCRIPT
    args = parse_args()
    set_seed(SEED)

    CACHE_ROOT = Path(args.cache_root)
    TRAIN_SCRIPT = Path(args.train_script)
    current_summary = locate_current_summary(Path(args.current_summary))
    out_dir = Path(args.out_dir) / args.split
    out_dir.mkdir(parents=True, exist_ok=True)

    print("=" * 150)
    print("FAPR-Depth v6 final paper comparison (locked verified baselines)")
    print("=" * 150)
    ours_key, ours_label = OURS_VARIANTS[args.ours_variant]
    print(f"mode={args.mode}, split={args.split}, region={args.region}")
    print(f"ours_variant={args.ours_variant} -> {ours_label}")
    print(f"current summary={current_summary}")
    print(f"output={out_dir}")
    print("baseline policy=locked verified full-split rows; replace only FAPR-Depth v6")
    print("final model=best_candidate.pth / Candidate benchmark")
    if args.mode == "direct":
        print(f"direct models={args.direct_models}, max_shards={args.max_shards}")
    print("=" * 150)

    current_rows, current_notes = load_current_rows(current_summary)
    sources: Dict[str, str] = {method: str(current_summary) for method in current_rows}
    notes: List[str] = list(current_notes)
    notes.append(
        "[role note] The final paper model is fixed as `candidate`: "
        "FAPR-Depth v6 Safe Anchor + bounded detail proposal. "
        "The second risk gate is reported only as an ablation."
    )
    notes.append(
        "[baseline policy] External baseline rows are frozen from the exact previous "
        "comparison CSVs. Only the FAPR-Depth v6 row is replaced."
    )

    # Internal FAPR table is always produced and includes all available v6 roles.
    internal_rows = dict(current_rows)

    # External baseline policy.
    #
    # Default paper mode: use the immutable rows from the previously verified
    # full-split comparison. This prevents diagnostic/full-image rows such as
    # RMSE≈0.247 from being selected merely because they contain more columns.
    #
    # --rediscover-external-baselines is retained only for auditing/debugging.
    summary_paths: List[Path] = []
    external_summary: Dict[str, Dict[str, float]] = {}
    external_sources: Dict[str, str] = {}
    external_notes: List[str] = []

    if args.mode == "summary" and not args.rediscover_external_baselines:
        external_summary = {
            method: dict(metrics)
            for method, metrics in LOCKED_VERIFIED_BASELINES.items()
        }
        external_sources = {
            method: LOCKED_BASELINE_SOURCE
            for method in LOCKED_VERIFIED_BASELINES
        }
        external_notes = [
            f"[locked verified baseline] {method} <- {LOCKED_BASELINE_SOURCE}"
            for method in LOCKED_VERIFIED_BASELINES
        ]
        print(
            "[Locked external baselines] "
            "DFNet/TODE/TDCNet/SwinDRNet/ReMake are fixed; only FAPR is refreshed."
        )
    else:
        def add_summary_path(path: Path) -> None:
            path = Path(path)
            if path.exists() and path.is_file() and path not in summary_paths:
                summary_paths.append(path)

        if not args.refresh_baseline_sources:
            for path in read_frozen_baseline_paths(out_dir):
                add_summary_path(path)
        for path in DEFAULT_EXTERNAL_SUMMARY_FILES:
            add_summary_path(path)
        for raw in args.extra_summary_csv:
            add_summary_path(Path(raw))
        if args.allow_recursive_scan:
            for path in find_candidate_summary_csvs(args.extra_summary_csv, out_dir):
                add_summary_path(path)

        external_summary, external_sources, external_notes = load_external_summary_rows(summary_paths)
        expected_external = ["DFNet", "TODE-Trans", "TDCNet", "SwinDRNet", "ReMake"]
        missing_external = [name for name in expected_external if name not in external_summary]

        if missing_external and args.mode == "summary":
            fallback_paths = restricted_historical_summary_scan(out_dir)
            for path in fallback_paths:
                add_summary_path(path)
            external_summary, external_sources, external_notes = load_external_summary_rows(summary_paths)
            missing_external = [name for name in expected_external if name not in external_summary]

        if missing_external and args.require_baselines and args.mode == "summary":
            source_text = "\n".join(f"- {path}" for path in summary_paths) or "<none>"
            raise RuntimeError(
                "Missing external baseline rows after diagnostic rediscovery: "
                + ", ".join(missing_external)
                + "\nChecked sources:\n"
                + source_text
            )

    notes.extend(external_notes)
    sources.update(external_sources)
    external_rows = dict(external_summary)

    # Hard sanity guard against the known bad diagnostic rows.
    bad_rows: List[str] = []
    for method in ("TODE-Trans", "TDCNet", "SwinDRNet"):
        metrics = external_rows.get(method, {})
        rmse = finite_float(metrics.get("rmse_mask"))
        mae = finite_float(metrics.get("mae_mask"))
        if rmse is None or mae is None or rmse > 0.10 or mae > 0.10:
            bad_rows.append(
                f"{method}(RMSE={rmse}, MAE={mae}, source={sources.get(method)})"
            )
    if bad_rows:
        raise RuntimeError(
            "Rejected implausible external diagnostic rows: "
            + "; ".join(bad_rows)
            + ". The paper table must use the locked verified baselines."
        )

    if args.mode == "summary":
        manifest_path = write_frozen_baseline_manifest(
            out_dir=out_dir,
            selected_sources=external_sources,
            candidate_paths=summary_paths,
        )
        print(f"[Frozen baseline manifest] {manifest_path}")
        notes.append(f"[frozen baseline manifest] {manifest_path}")

    if args.mode == "direct":
        requested_models = parse_direct_models(args.direct_models)
        direct_rows, direct_sources, direct_notes = evaluate_direct_external(
            split=args.split,
            max_shards=args.max_shards,
            requested_models=requested_models,
            out_dir=out_dir,
            force=args.force_direct,
        )
        # Directly recomputed rows override potentially ambiguous old summary rows.
        external_rows.update(direct_rows)
        sources.update(direct_sources)
        notes.extend(direct_notes)
        if args.max_shards > 0:
            warning = (
                "[PROTOCOL WARNING] Direct external rows were computed on a subset, while the current FAPR "
                "summary represents the full split. Use --max-shards 0 for a formal table."
            )
            notes.append(warning)
            print(warning)

    if ours_key not in current_rows:
        diagnostic = "\n".join(current_notes[-4:])
        raise KeyError(
            f"Requested --ours-variant={args.ours_variant!r}, but `{ours_key}` was not found in "
            f"{current_summary}. Parsed current rows: {sorted(current_rows)}\n"
            f"Current-summary diagnostics:\n{diagnostic}"
        )

    # Only methods with a real row are inserted. Missing/unavailable models are not displayed.
    main_rows: Dict[str, Dict[str, float]] = {}
    if "Raw Depth" in current_rows:
        main_rows["Raw Depth"] = current_rows["Raw Depth"]
    for method in ["DFNet", "TODE-Trans", "TDCNet", "SwinDRNet"]:
        if method in external_rows:
            main_rows[method] = external_rows[method]
    if "FDCT" in current_rows:
        main_rows["FDCT"] = current_rows["FDCT"]
    if "ReMake" in external_rows:
        main_rows["ReMake"] = external_rows["ReMake"]
    main_rows[ours_label] = current_rows[ours_key]
    sources[ours_label] = str(current_summary)

    expected = list(MAIN_METHOD_ORDER_BASE) + [ours_label]
    missing = [method for method in expected if method not in main_rows]
    if missing:
        notes.append("[omitted unavailable methods] " + ", ".join(missing))
        print("[Info] Omitted unavailable methods:", ", ".join(missing))

    write_comparison_outputs(
        out_dir=out_dir,
        split=args.split,
        region=args.region,
        main_rows_by_method=main_rows,
        internal_rows_by_method=internal_rows,
        sources=sources,
        notes=notes,
        mode=args.mode,
        max_shards=args.max_shards,
        main_order=expected,
        ours_label=ours_label,
        ours_variant=args.ours_variant,
    )


if __name__ == "__main__":
    main()
