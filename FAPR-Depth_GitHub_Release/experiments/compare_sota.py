def find_candidate_summary_csvs(extra_csvs: Sequence[str], out_dir: Path) -> List[Path]:
    paths: List[Path] = []

    def add(path: Path) -> None:
        path = Path(path)
        if path.exists() and path.is_file() and path not in paths:
            try:
                # Do not recursively consume our own newly generated tables.
                if out_dir.resolve() in path.resolve().parents:
                    return
            except Exception:
                pass
            paths.append(path)

    for path in DEFAULT_EXTERNAL_SUMMARY_FILES:
        add(path)
    for raw in extra_csvs:
        add(Path(raw))

    patterns = [
        "outputs/**/dfnet*summary*.csv",
        "outputs/**/remake*summary*.csv",
        "outputs/**/tode*summary*.csv",
        "outputs/**/tdcnet*summary*.csv",
        "outputs/**/swindrnet*summary*.csv",
        "outputs/**/dreds*summary*.csv",
        "outputs/**/fair_external_comparison*_all_metrics.csv",
        "outputs/**/fair_external_comparison*.csv",
    ]
    for pattern in patterns:
        for path in PROJECT_ROOT.glob(pattern):
            add(path)
    return paths



def historical_baseline_manifest_path(out_dir: Path) -> Path:
    return Path(out_dir) / "frozen_external_baseline_sources.json"


def read_frozen_baseline_paths(out_dir: Path) -> List[Path]:
    """Read paths selected by a previous successful run."""
    manifest = historical_baseline_manifest_path(out_dir)
    if not manifest.exists():
        return []
    try:
        data = json.loads(manifest.read_text(encoding="utf-8"))
    except Exception as exc:
        print(f"[Baseline manifest warning] Could not read {manifest}: {exc!r}")
        return []

    paths: List[Path] = []
    for raw in data.get("selected_sources", {}).values():
        path = Path(raw)
        if path.exists() and path.is_file() and path not in paths:
            paths.append(path)
    if paths:
        print(f"[Baseline manifest] Reusing {len(paths)} frozen source CSV(s): {manifest}")
    return paths


def restricted_historical_summary_scan(out_dir: Path) -> List[Path]:
    """Locate old baseline CSVs without consuming current FAPR/smoke outputs.

    This is intentionally narrower than a general recursive scan. It only looks
    for filenames historically associated with the external baselines.
    """
    paths: List[Path] = []
    excluded_dir_tokens = {
        "fapr_depth_v6_unified_protocol_test",
        "fapr_depth_v6_paper_final_comparison",
        "fapr_depth_v6_paper_final_comparison_v2",
        "fapr_depth_v6_complete_test",
    }

    def add(path: Path) -> None:
        path = Path(path)
        if not path.exists() or not path.is_file() or path in paths:
            return
        low_parts = {part.lower() for part in path.parts}
        if any(token in low_parts for token in excluded_dir_tokens):
            return
        try:
            if Path(out_dir).resolve() in path.resolve().parents:
                return
        except Exception:
            pass
        paths.append(path)

    patterns = [
        "outputs/**/dfnet*summary*.csv",
        "outputs/**/remake*summary*.csv",
        "outputs/**/tode*summary*.csv",
        "outputs/**/tdcnet*summary*.csv",
        "outputs/**/tdc*summary*.csv",
        "outputs/**/swindrnet*summary*.csv",
        "outputs/**/dreds*summary*.csv",
        "outputs/**/fair_external_comparison*_all_metrics.csv",
        "outputs/**/fair_external_comparison*.csv",
        "outputs/**/tage_depth_main_comparison*.csv",
        "outputs/**/main_comparison*test*mask*.csv",
    ]
    for pattern in patterns:
        for path in PROJECT_ROOT.glob(pattern):
            add(path)

    return sorted(paths, key=lambda p: str(p).lower())


