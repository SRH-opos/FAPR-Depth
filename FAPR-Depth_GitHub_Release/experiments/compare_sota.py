def set_seed(seed: int = SEED) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)
        torch.backends.cudnn.benchmark = True


def import_module_from_path(module_name: str, path: Path):
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(f"Python module not found: {path}")
    spec = importlib.util.spec_from_file_location(module_name, str(path))
    module = importlib.util.module_from_spec(spec)
    sys.modules[module_name] = module
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


def finite_float(value: Any) -> Optional[float]:
    if value is None:
        return None
    if isinstance(value, (int, float, np.number)):
        x = float(value)
        return x if np.isfinite(x) else None
    text = str(value).strip()
    if not text or text.lower() in {"nan", "none", "null", "-"}:
        return None
    try:
        x = float(text)
        return x if np.isfinite(x) else None
    except (TypeError, ValueError):
        return None


def average_dicts(rows: Sequence[Dict[str, float]]) -> Dict[str, float]:
    if not rows:
        return {}
    keys = sorted(set().union(*(row.keys() for row in rows)))
    out: Dict[str, float] = {}
    for key in keys:
        vals = [finite_float(row.get(key)) for row in rows]
        vals = [v for v in vals if v is not None]
        if vals:
            out[key] = float(np.mean(vals))
    return out


def selection_score(row: Dict[str, float]) -> Optional[float]:
    required = ["mae_mask", "rmse_mask", "boundary", "rmse_all"]
    vals = [finite_float(row.get(k)) for k in required]
    if any(v is None for v in vals):
        return None
    mae_mask, rmse_mask, boundary, rmse_all = vals
    return float(mae_mask + rmse_mask + 0.5 * boundary + 0.15 * rmse_all)


def write_csv(path: Path, rows: Sequence[Dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        path.write_text("", encoding="utf-8")
        return
    keys: List[str] = []
    seen = set()
    for row in rows:
        for key in row.keys():
            if key not in seen:
                seen.add(key)
                keys.append(key)
    with open(path, "w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=keys, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)


def write_json(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")


def load_csv_rows(path: Path) -> List[Dict[str, Any]]:
    if not path.exists():
        return []
    try:
        with open(path, "r", encoding="utf-8-sig", newline="") as f:
            return list(csv.DictReader(f))
    except Exception as exc:
        print(f"[WARN] Cannot read CSV {path}: {exc}")
        return []


def row_name(row: Dict[str, Any]) -> str:
    """Return the most useful display/model name for generic CSV rows.

    Prefer an explicit method column.  The v6 combined comparison CSV contains both
    ``method`` and ``variant``; using ``variant`` first collapses multiple checkpoint
    roles to names such as ``Safe benchmark`` and makes the current FAPR rows
    impossible to identify.
    """
    for key in ["method", "Method", "variant", "Variant", "method_key", "name", "model"]:
        text = str(row.get(key, "")).strip()
        if text:
            return text
    return ""


def row_aliases(row: Dict[str, Any]) -> List[str]:
    """Collect every non-empty name-like field from a CSV row.

    This is intentionally separate from :func:`row_name`: current FAPR rows need
    exact lookup by the human-facing ``method`` label, while older external CSVs
    sometimes expose the model only through ``variant`` or ``name``.
    """
    aliases: List[str] = []
    seen = set()
    for key in ["method", "Method", "variant", "Variant", "method_key", "name", "model"]:
        text = str(row.get(key, "")).strip()
        if text and text not in seen:
            seen.add(text)
            aliases.append(text)
    return aliases


def normalize_threshold(value: Optional[float]) -> Optional[float]:
    if value is None:
        return None
    # Some summaries store threshold accuracy as a percentage.
    return value / 100.0 if value > 1.5 else value


def first_metric(row: Dict[str, Any], aliases: Sequence[str], threshold: bool = False) -> Optional[float]:
    for key in aliases:
        if key in row:
            value = finite_float(row.get(key))
            if value is not None:
                return normalize_threshold(value) if threshold else value
    return None


def standardize_metrics(row: Dict[str, Any]) -> Dict[str, float]:
    """Normalize metrics from current and previous evaluation wrappers.

    Generic MAE/RMSE/REL/threshold columns are treated as transparent-mask metrics,
    because the old paper comparison summaries use those names for the mask table.
    Whole-image values are accepted only from explicit *_all columns.
    """
    out: Dict[str, float] = {}
    aliases: Dict[str, Tuple[Sequence[str], bool]] = {
        "mae_all": (["mae_all", "MAE_all", "all_mae"], False),
        "rmse_all": (["rmse_all", "RMSE_all", "all_rmse"], False),
        "mae_mask": (["mae_mask", "MAE_mask", "MaskedMAE", "masked_mae", "MAE", "mae"], False),
        "rmse_mask": (["rmse_mask", "RMSE_mask", "MaskedRMSE", "masked_rmse", "RMSE", "rmse"], False),
        "rel_mask": (["rel_mask", "REL_mask", "MaskedREL", "masked_rel", "REL", "rel"], False),
        "delta_105": ([
            "delta_105", "delta_1_05_mask", "d1.05_mask", "delta105_mask",
            "MaskedThreshold@1.05", "Threshold@1.05", "threshold_1_05_mask",
            "delta_1_05", "d1.05",
        ], True),
        "delta_110": ([
            "delta_110", "delta_1_10_mask", "d1.10_mask", "delta110_mask",
            "MaskedThreshold@1.10", "Threshold@1.10", "threshold_1_10_mask",
            "delta_1_10", "d1.10",
        ], True),
        "delta_125": ([
            "delta_125", "delta_1_25_mask", "d1.25_mask", "delta125_mask",
            "MaskedThreshold@1.25", "Threshold@1.25", "threshold_1_25_mask",
            "delta_1_25", "d1.25",
        ], True),
        "boundary": (["boundary", "mae_boundary", "Boundary", "boundary_mae"], False),
        "reliable_bg_disturbance": (["reliable_bg_disturbance", "BG", "bg"], False),
        "score": (["score", "Score"], False),
    }
    for target, (keys, is_threshold) in aliases.items():
        value = first_metric(row, keys, threshold=is_threshold)
        if value is not None:
            out[target] = value
    if "score" not in out:
        score = selection_score(out)
        if score is not None:
            out["score"] = score
    return out


def name_matches(name: str, patterns: Sequence[str]) -> bool:
    low = name.lower()
    return all(pattern.lower() in low for pattern in patterns)


def protocol_bonus(row: Dict[str, Any], source_path: Path) -> int:
    text = " ".join(
        str(row.get(k, ""))
        for k in ["table_group", "protocol", "region", "split", "variant", "method"]
    ).lower()
    source_text = str(source_path).lower()
    bonus = 0
    if "mask" in text or "transparent" in text:
        bonus += 12
    if "test" in text or "test" in source_text:
        bonus += 5
    if "sample" in text and "mean" in text:
        bonus += 3
    if "raw" in text and "raw depth" not in text:
        bonus -= 3
    return bonus


